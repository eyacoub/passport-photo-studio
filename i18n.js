let language = "ar";
const texts = new WeakMap();
const attributes = new WeakMap();
export const message = (key, params = {}) => ({ key, params });
export function translate(value) {
  if (value == null) return "";
  if (typeof value === "number") return new Intl.NumberFormat(language === "ar" ? "ar-u-nu-arab" : "en").format(value);
  const { key, params = {} } = typeof value === "object" ? value : { key: value };
  const template = language === "ar" ? (arabic[key] ?? key) : key;
  return template.replace(/\{(\w+)\}/g, (_, name) => translate(params[name]));
}
function render(element) {
  if (element.hasAttribute("data-i18n")) {
    element.textContent = translate(texts.has(element) ? texts.get(element) : element.dataset.i18n);
  }
  for (const name of ["aria-label", "alt"]) {
    if (element.hasAttribute(`data-i18n-${name}`)) {
      element.setAttribute(name, translate(attributes.get(element)?.[name] ?? element.getAttribute(`data-i18n-${name}`)));
    }
  }
}
export function bindText(element, value) {
  texts.set(element, value);
  element.setAttribute("data-i18n", "");
  render(element);
}
export function bindAttribute(element, name, value) {
  attributes.set(element, { ...attributes.get(element), [name]: value });
  element.setAttribute(`data-i18n-${name}`, "");
  render(element);
}
export function localizedError(key, params = {}) {
  const error = new Error(key);
  error.userMessage = message(key, params);
  return error;
}
function applyLanguage(value) {
  language = value === "en" ? "en" : "ar";
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  document.title = translate("Passport Photo Studio");
  document.querySelectorAll("[data-i18n], [data-i18n-aria-label], [data-i18n-alt]").forEach(render);
  document.getElementById("languageSelect").value = language;
  try { localStorage.setItem("passport_language", language); } catch {}
}
export function initializeLanguage() {
  let saved;
  try { saved = localStorage.getItem("passport_language"); } catch {}
  applyLanguage(saved);
  document.getElementById("languageSelect").addEventListener("change", event => applyLanguage(event.target.value));
}
